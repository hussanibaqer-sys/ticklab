    public static IEnumerable<DrawingMediaDefinition> ForType(string type) =>
        type.ToLowerInvariant() switch
        {
            "stickers" => Stickers,
            "emojis" => Emojis,
            _ => Icons
        };

    public static DrawingMediaDefinition? Find(string type, string key) =>
        ForType(type).FirstOrDefault(item =>
            string.Equals(item.Key, key, StringComparison.OrdinalIgnoreCase));

    public static string Encode(DrawingMediaDefinition media) =>
        $"{Prefix}:{media.Type}:{media.Key}";

    public static bool TryDecode(
        string? value,
        out DrawingMediaDefinition? media)
    {
        media = null;
        if (string.IsNullOrWhiteSpace(value))
            return false;

        string[] parts = value.Split(':', 3, StringSplitOptions.TrimEntries);
        if (parts.Length != 3 || !string.Equals(parts[0], Prefix, StringComparison.Ordinal))
            return false;

        media = Find(parts[1], parts[2]);
        return media is not null;
    }

    private static DrawingMediaDefinition Icon(
        string key,
        string label,
        string mark,
        string primary,
        string secondary) =>
        new("icons", key, label, mark, primary, secondary);

    private static DrawingMediaDefinition Sticker(
        string key,
        string label,
        string primary,
        string secondary) =>
        new("stickers", key, label, label, primary, secondary);

    private static DrawingMediaDefinition Emoji(
        string key,
        string label,
        string mark,
        string category) =>
        new("emojis", key, label, mark, "#F5B544", "#FFE6A6", category);
